// Function to get a random integer between min and max (inclusive) using the LCG
function getDeterministicRandomInt(seed, min, max) {
    const lcg = new LCG(seed);
    const randomFloat = lcg.nextFloat();
    return Math.floor(randomFloat * (max - min + 1)) + min;
}

function generateDungeon(name) {
    playerEnergy = ["red", "blue", "green", "wild"]
    playerCoins = 0;
    var dungeonFinalSeed = dungeonSeed * name.charCodeAt(0) * name.charCodeAt(1) * name.charCodeAt(2);
    dungeonName = name;
    var playerCoord = [0, 0];
    //Create the central tile
    dungeonTileArray.push({x: 0, y: 0, type: "start"});
    var offshootArray = [
        {x: 0, y: 0, direction: "up"},
        {x: 0, y: 0, direction: "down"},
        {x: 0, y: 0, direction: "left"},
        {x: 0, y: 0, direction: "right"},
    ];
    var offshootsAllowed = 10;
    while (offshootArray.length > 0) {
        //Use the first offshoot in the array and begin creating tiles in that direction
        var offshootSquareChance = 150;
        var offshootOffshootChance = 20;
        var x = offshootArray[0].x;
        var y = offshootArray[0].y;
        while (offshootSquareChance > 0) {
            var funkyNumber = offshootArray[0].direction.charCodeAt(0) + x + y;
            var funkySeed = dungeonFinalSeed * funkyNumber * funkyNumber;
            //Use the offshootSquareChance as a percentage chance to create a square room, using the dungeon seed to get a deterministic result
            var d100 = getDeterministicRandomInt(funkySeed, 0, 100);
            d100 = 100-d100;
            if (d100 < offshootSquareChance) {
                console.info(offshootSquareChance)
                console.info(d100)
                offshootSquareChance -= d100;
                offshootOffshootChance += d100*2;
                console.info(offshootOffshootChance)
                if (offshootOffshootChance > 180 && offshootsAllowed > 0) {
                    offshootOffshootChance = 0;
                    offshootsAllowed -= 1;
                    var directionArray = ["up", "down", "left", "right"];
                    switch (offshootArray[0].direction) {
                        case "up":
                            directionArray = directionArray.filter(direction => direction != "up");
                            directionArray = directionArray.filter(direction => direction != "down");
                        break;
                        case "down":
                            directionArray = directionArray.filter(direction => direction != "up");
                            directionArray = directionArray.filter(direction => direction != "down");
                        break;
                        case "left":
                            directionArray = directionArray.filter(direction => direction != "left");
                            directionArray = directionArray.filter(direction => direction != "right");
                        break;
                        case "right":
                            directionArray = directionArray.filter(direction => direction != "left");
                            directionArray = directionArray.filter(direction => direction != "right");
                        break;
                    }
                    var directionPicker = getDeterministicRandomInt(funkySeed, 0, directionArray.length - 1);
                    var newDirection = directionArray[directionPicker];
                    var newOffshoot = {x: x, y: y, direction: newDirection};
                    offshootArray.push(newOffshoot);
                }
            }
            else {
                offshootSquareChance = 0;
            }
            switch (offshootArray[0].direction) {
                case "up":
                    var newTile = {x: x, y: y - 1, type: "blank"};
                    y -= 1;
                break;
                case "down":
                    var newTile = {x: x, y: y + 1, type: "blank"};
                    y += 1;
                break;
                case "left":
                    var newTile = {x: x - 1, y: y, type: "blank"};
                    x -= 1;
                break;
                case "right":
                    var newTile = {x: x + 1, y: y, type: "blank"};
                    x += 1;
                break;
            }
            dungeonTileArray.push(newTile);
        }
        //Remove the offshoot from the array
        offshootArray.shift();
    }
    //Erase duplicate tiles
    var uniqueTiles = [];
    for (var tile of dungeonTileArray) {
        var unique = true;
        for (var uniqueTile of uniqueTiles) {
            if (tile.x == uniqueTile.x && tile.y == uniqueTile.y) {
                unique = false;
            }
        }
        if (unique) {
            uniqueTiles.push(tile);
        }
    }
    dungeonTileArray = uniqueTiles;
    //Find any tiles surrounded by other tiles and remove them, except for the central tile
    var surroundedTiles = [];
    for (var tile of dungeonTileArray) {
        var surrounded = true;
        var x = tile.x;
        var y = tile.y;
        var surroundingTiles = [
            {x: x, y: y - 1},
            {x: x - 1, y: y},
            {x: x - 1, y: y - 1},
            {x: x, y: y + 1},
            {x: x + 1, y: y},
            {x: x + 1, y: y + 1},
        ];
        for (var surroundingTile of surroundingTiles) {
            var found = false;
            for (var dungeonTile of dungeonTileArray) {
                if (dungeonTile.x == surroundingTile.x && dungeonTile.y == surroundingTile.y) {
                    found = true;
                }
            }
            if (!found) {
                surrounded = false;
            }
        }
        if (surrounded && !(x == 0 && y == 0)) {
            //Remove the tile
            dungeonTileArray = dungeonTileArray.filter(dungeonTile => dungeonTile.x != x || dungeonTile.y != y);
        }
    }

    //Find the farthest tile from the central tile and change the type to "boss"
    var farthestTile = {x: 0, y: 0, distance: 0};
    for (var tile of dungeonTileArray) {
        var distance = Math.abs(tile.x) + Math.abs(tile.y);
        if (distance > farthestTile.distance) {
            farthestTile = {x: tile.x, y: tile.y, distance: distance};
        }
    }
    for (var tile of dungeonTileArray) {
        if (tile.x == farthestTile.x && tile.y == farthestTile.y) {
            tile.type = "boss";
        }
    }

    //Assign a type to all tiles except the central and boss tiles
    var tileTypes = [
        {type: "red", count: 0},
        {type: "blue", count: 0},
        {type: "green", count: 0},
        {type: "random", count: 0, max: 4},
        {type: "shop", count: 0, max: 2},
        {type: "chest", count: 0, max: 2},
    ];

    var typeCount = 0;
    for (var tile of dungeonTileArray) {
        if (tile.type != "start" && tile.type != "boss") {
            if (typeCount > 2) {
                if (tileTypes[0].count < 3) {
                    typeCount = 0;
                }
                if (tileTypes[typeCount].count >= tileTypes[typeCount].max) {
                    typeCount = 0;
                }
            }
            tile.type = tileTypes[typeCount].type;
            tileTypes[typeCount].count += 1;
            if (typeCount > tileTypes.length-2) {
                typeCount = 0;
            }
            else {
                typeCount += 1;
            }
        }
    }
    printDungeon();
}

