def crop_to_ratio(image, target_width, target_height, centre_fraction):
    target_ratio = target_width / target_height
    width, height = image.size
    crop_height = int(width / target_ratio)
    if crop_height > height:
        crop_height = height
        crop_width = int(height * target_ratio)
    else:
        crop_width = width
    centre_y = int(height * centre_fraction)
    top = max(0, min(height - crop_height, centre_y - crop_height // 2))
    left = (width - crop_width) // 2
    return image.crop((left, top, left + crop_width, top + crop_height)).resize(
        (target_width, target_height), Image.LANCZOS)


