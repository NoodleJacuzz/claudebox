def tint(image, color, strength):
    flat = Image.new("RGBA", image.size, color + (255,))
    blended = Image.blend(image.convert("RGBA"), flat, strength)
    blended.putalpha(image.getchannel("A"))
    return blended


def shift_hue(image, degrees):
    alpha = image.getchannel("A")
    h, s, v = image.convert("RGB").convert("HSV").split()
    h = h.point(lambda value: int((value + degrees * 255 / 360) % 256))
    result = Image.merge("HSV", (h, s, v)).convert("RGBA")
    result.putalpha(alpha)
    return result


def adjust(image, brightness=1.0, saturation=1.0, contrast=1.0):
    alpha = image.getchannel("A")
    rgb = image.convert("RGB")
    if brightness != 1.0:
        rgb = ImageEnhance.Brightness(rgb).enhance(brightness)
    if saturation != 1.0:
        rgb = ImageEnhance.Color(rgb).enhance(saturation)
    if contrast != 1.0:
        rgb = ImageEnhance.Contrast(rgb).enhance(contrast)
    result = rgb.convert("RGBA")
    result.putalpha(alpha)
    return result


def blotches(image, count, radius_fraction, color, seed):
    """Soft coloured blobs clipped to the silhouette. Stands in for wounds on a hurt-tier sprite."""
    width, height = image.size
    alpha = image.getchannel("A")
    layer = Image.new("RGBA", image.size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(layer)

    state = seed
    radius = max(2, int(min(width, height) * radius_fraction))
    for _ in range(count):
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        x = int((state >> 8) % width)
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        y = int((state >> 8) % height)
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        size = radius // 2 + int((state >> 8) % radius)
        draw.ellipse([x - size, y - size, x + size, y + size], fill=color + (200,))

    layer = layer.filter(ImageFilter.GaussianBlur(radius * 0.35))
    layer.putalpha(ImageChops.multiply(layer.getchannel("A"), alpha))
    return Image.alpha_composite(image, layer)


def lean(image, degrees, lift_fraction):
    """Rotates and lifts a sprite. Stands in for an action pose without redrawing the figure."""
    width, height = image.size
    rotated = image.rotate(degrees, resample=Image.BICUBIC, expand=False,
                           center=(width // 2, int(height * 0.92)))
    if lift_fraction:
        shifted = Image.new("RGBA", image.size, (0, 0, 0, 0))
        shifted.paste(rotated, (0, -int(height * lift_fraction)), rotated)
        return shifted
    return rotated


def head_crop(image, size):
    """A square crop around the head, for the portrait. Sources are full-body 1:2, head at the top."""
    width, height = image.size
    box = int(width * 0.62)
    left = (width - box) // 2
    top = int(height * 0.035)
    cropped = image.crop((left, top, left + box, top + box))
    return cropped.resize((size, size), Image.LANCZOS)


PORTRAIT_SIZE = 256

# Sprites are capped at this height, and it is also the RECOMMENDED DELIVERY SIZE for real art.
#
# The reasoning: a fighter occupies at most ~60% of the stage height. On a 1080p screen that is ~650
# display pixels, so ~1300 covers a 2x/retina panel with room to spare. The 1408x2816 source art is
# more than twice that in each direction and four times the pixels -- which cost 16MB across the
# generated set and visibly delayed the first paint of a battle for no visual gain whatsoever.
#
# Raise this if the game ever renders fighters larger; there is no reason to ship more.
SPRITE_MAX_HEIGHT = 1300


def cap_height(image, maximum=None):
    """Downscales to the sprite height cap, preserving aspect. Never upscales."""
    limit = SPRITE_MAX_HEIGHT if maximum is None else maximum
    if image.height <= limit:
        return image
    width = max(1, round(image.width * limit / image.height))
    return image.resize((width, limit), Image.LANCZOS)


