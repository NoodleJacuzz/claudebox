def build_pose_set(standing, *folder_parts, portrait=None, exposed=False, only=None, bare_beside_real_combat=False):
    """Writes 0-portrait plus every tier and pose for one outfit or enemy variant.

    `only` is a set of file names: given, nothing outside it is written (see ENEMY_FILES).

    Skips any file a previous run did not claim -- that means real art has replaced the placeholder,
    and overwriting it would destroy an art pass. `portrait` is a finished crop; omitted, the character
    head crop is used. `exposed` also writes the Exposed cut-in's own picture for the outfit.
    """
    folder_path = os.path.join(ART, *folder_parts)
    os.makedirs(folder_path, exist_ok=True)
    existing = set(os.listdir(folder_path)) if os.path.isdir(folder_path) else set()
    claimed = set(read_manifest(folder_path))
    written = []
    kept = []

    # An enemy whose `1-combat` is real art gets NO generated files beside it. A generated `1-offense` is
    # cut from the old stand-in drawing, so the enemy would turn into a different creature every time it
    # attacked. The game falls back to `1-combat` for the attack until a real `1-offense` is drawn.
    # ENEMIES ONLY (`bare_beside_real_combat`): a character's tilted stand-ins are Noodle's named backups
    # and are wanted beside her real art.
    real_combat = bare_beside_real_combat and "1-combat.webp" in existing and "1-combat.webp" not in claimed

    def emit(image, name):
        if only is not None and (name not in only or real_combat):
            return
        # Present but unclaimed = real art. Leave it, and leave it out of the new manifest.
        if FORCE is False and name in existing and name not in claimed:
            kept.append(name)
            return
        save(image, *(folder_parts + (name,)))
        written.append(name)

    # The portrait crops from the FULL-RESOLUTION source before the cap, so the face stays sharp.
    emit(head_crop(standing, PORTRAIT_SIZE) if portrait is None else portrait, "0-portrait.webp")
    standing = cap_height(standing)
    tier_sources = {1: standing, 2: to_hurt(standing)}
    for tier in TIERS:
        for pose in POSES:
            emit(POSE_RECIPES[pose](tier_sources[tier]), "%d-%s.webp" % (tier, pose))
    if exposed:
        emit(exposed_recipe(tier_sources[2]), "exposed.webp")

    write_manifest(folder_path, written)
    return written, kept


