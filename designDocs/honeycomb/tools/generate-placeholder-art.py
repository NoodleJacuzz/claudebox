# How much of the busiest row or column must be opaque for it to count as FIGURE when reading an
# outline. Stray specks in a source canvas (smol has several) would otherwise widen it to the canvas.
PORTRAIT_OUTLINE_FLOOR = 0.04
PORTRAIT_OPAQUE_ALPHA = 128
# Every source drawing now belongs to an enemy: smol, brute, caster, warrior, matriarch, juggernaut,
# gardener, sage, alchemist, shield and scavenger are all mapped in ENEMY_SOURCES above.


def figure_outline(image):
    """The box the figure itself fills: rows and columns carrying at least PORTRAIT_OUTLINE_FLOOR of the
    busiest one's opaque pixels, so a few stray specks do not count."""
    width, height = image.size
    mask = image.getchannel("A").point(lambda value: 255 if value >= PORTRAIT_OPAQUE_ALPHA else 0)
    pixels = mask.load()
    column_counts = [0] * width
    row_counts = [0] * height
    for y in range(height):
        for x in range(width):
            if pixels[x, y]:
                column_counts[x] += 1
                row_counts[y] += 1

    def span(counts):
        floor = max(counts) * PORTRAIT_OUTLINE_FLOOR
        filled = [index for index, count in enumerate(counts) if count > floor]
        return (filled[0], filled[-1] + 1) if filled else (0, len(counts))

    left, right = span(column_counts)
    top, bottom = span(row_counts)
    return (left, top, right, bottom)


def portrait_crop(image, size, placement=None):
    """A square face crop for an enemy. Sources vary in shape, so the default reads the figure's outline:
    a box as wide as the figure (never taller than it), from the figure's top."""
    width, height = image.size
    if placement is not None:
        box = int(width * placement["box"])
        left = int(width * placement["x"] - box / 2)
        top = int(height * placement["y"])
    else:
        bbox = figure_outline(image)
        figure_width = bbox[2] - bbox[0]
        figure_height = bbox[3] - bbox[1]
        box = min(figure_width, figure_height)
        left = (bbox[0] + bbox[2]) // 2 - box // 2
        top = bbox[1]
    cropped = image.crop((left, top, left + box, top + box))
    return cropped.resize((size, size), Image.LANCZOS)


def apply_recipe(image, recipe):
    if recipe is None:
        return image
    result = shift_hue(image, recipe.get("hue", 0))
    result = adjust(result, brightness=recipe.get("brightness", 1.0),
                    saturation=recipe.get("saturation", 1.0))
    blot = recipe.get("blot")
    if blot:
        result = blotches(result, blot["count"], blot["radius"], blot["color"], blot["seed"])
    scale = recipe.get("scale", 1.0)
    if scale != 1.0:
        result = result.resize((max(1, int(image.width * scale)), max(1, int(image.height * scale))),
                               Image.LANCZOS)
    return result



