def frame_outline(size, cut, inset, corners):
    """The frame's outline `inset` pixels in from the edge, as a list of points. The cut shrinks as the
    outline moves in, so every inner diagonal stays parallel to the outer one.

    corners "all": a closed octagon, clockwise from the top-left cut.
    corners "top": an OPEN path for a tab -- up the left side, across the top, down the right -- with no
    bottom edge, since a tab sits on the panel it belongs to.
    """
    s = size - 1
    c = max(0.0, cut - inset * 0.414)
    i = inset
    if corners == "all":
        return [(i + c, i), (s - i - c, i), (s - i, i + c), (s - i, s - i - c),
                (s - i - c, s - i), (i + c, s - i), (i, s - i - c), (i, i + c), (i + c, i)]
    return [(i, s), (i, i + c), (i + c, i), (s - i - c, i), (s - i, i + c), (s - i, s)]


