"""Generates Honeycomb Catacombs' PLACEHOLDER art from the handful of real source images.

Not part of the game. Nothing in scripts/ runs this or knows it exists; it is a one-shot tool for
producing stand-in assets so the game reads correctly before it is drawn properly.

THE LAYOUT IT PRODUCES  (matches honeycomb-art.js -- change both together)

    characters/<character>/<outfit>/0-portrait      the face, for rosters and rails
    characters/<character>/<outfit>/1-basic         standing, healthy
    characters/<character>/<outfit>/1-damaged       recoiling, healthy
    characters/<character>/<outfit>/1-offense       attacking, healthy
    characters/<character>/<outfit>/1-passive       non-attack action, healthy
    characters/<character>/<outfit>/2-*             the same four, hurt
    enemies/<enemy>/<variant>/...                   identical shape

Eight sprites plus a portrait per outfit, and nothing more. The numeric prefix is a health tier
(1 healthy, 2 hurt); the word after it is a pose. Files therefore sort into a readable order inside
each folder -- portrait, then every healthy pose, then every hurt pose -- so an art pass can see at a
glance what exists and what is missing.

WHAT IS DELIBERATELY NOT GENERATED

  * State art. Statuses are drawn as CSS filters over the base sprite (honeycomb.art.stateArray),
    which costs zero images. Only a status that genuinely deserves a drawn pose gets a folder, and
    that is an art decision rather than something to bulk-generate.
  * Symbolic icons -- statuses, resources, node types, intents. Those are inline SVG generated at
    runtime by honeycomb.ui.glyph, which is the right home for a shape that will become a drawn icon.

Dropping a real .webp into any of these paths makes the game prefer it immediately, with no code
change: the resolver walks a fallback chain and stops at the first file that loads.

Rerunning is safe and deterministic: every output is overwritten from the sources, no output is ever
a source, and the noise functions are seeded hash walks rather than `random`.

Usage:
    python "!designDocs/honeycomb/tools/generate-placeholder-art.py"
    python "!designDocs/honeycomb/tools/generate-placeholder-art.py" --force

Without --force the script never touches a file it did not write itself, so real art dropped in during
an art pass is safe. Use --force to reclaim every path as a placeholder again -- which is also what a
first run on a tree that predates the manifests needs, since files with no manifest are indistinguish-
able from real art and are protected by default.
"""
