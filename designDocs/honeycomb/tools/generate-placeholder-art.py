# How each pose is derived from the standing image. Real art replaces these; the point is that every
# pose EXISTS so the fallback chain is exercised and the game reads correctly.
POSE_RECIPES = {
    # basic is the source itself, untouched.
    "basic": lambda image: image,
    # combat stands in as basic until a side-facing drawing replaces it. A real <name>-combat drawing
    # dropped into the output folder wins under the manifest rule, exactly as any other art pass does.
    "combat": lambda image: image,
    # damaged: knocked back and reddened.
    "damaged": lambda image: adjust(tint(lean(image, -7, 0.0), (200, 60, 50), 0.30), brightness=1.08),
    # offense: leaning into a swing. SESSION 35 dropped the mirror this used to add as a cheap second
    # frame: once art faces sideways (the `combat` stance) and the engine flips sprites by side
    # (honeycomb.art.spriteTransform), a mirrored attack pose turns the fighter away from the enemy it
    # is hitting. A deeper lean carries the beat instead, and it reads the same on front-facing art.
    "offense": lambda image: lean(image, 9, 0.03),
    # passive: a smaller, calmer lift, for skills and gestures.
    "passive": lambda image: lean(image, 2, 0.015),
}

# The hurt tier is the healthy tier, worn down, before the pose recipe is applied.
def to_hurt(image):
    return blotches(adjust(image, brightness=0.86, saturation=0.78), 12, 0.05, (135, 18, 22), 29)


