def has_real_image(*folder_parts):
    """Whether a folder holds any picture that is not on its manifest, which means somebody drew it."""
    folder_path = os.path.join(ART, *folder_parts)
    if not os.path.isdir(folder_path):
        return False
    claimed = set(read_manifest(folder_path))
    return any(name.endswith(".webp") and name not in claimed for name in os.listdir(folder_path))


# An alt outfit with no drawing of its own gets every default picture under the same name, through its
# colour recipe. The PNG original is recoloured when there is one, then scaled to the game's size.
# An alt with a real drawing gets the usual tilted stand-ins instead (build_pose_set).
OUTFIT_COPY_SHAPE_TOLERANCE = 0.01


def build_outfit_copies(character, outfit, recipe):
    default_folder = os.path.join(ART, "characters", character, "default")
    outfit_folder = os.path.join(ART, "characters", character, outfit)
    os.makedirs(outfit_folder, exist_ok=True)
    default_claimed = set(read_manifest(default_folder))
    written = []
    copied_drawings = []
    for name in sorted(os.listdir(default_folder)):
        if not name.endswith(".webp"):
            continue
        game_copy = Image.open(os.path.join(default_folder, name)).convert("RGBA")
        original_path = os.path.join(PNG_ARCHIVE, "characters", character, "default", name[:-len(".webp")] + ".png")
        original = Image.open(original_path).convert("RGBA") if os.path.exists(original_path) else None
        # An original of another SHAPE was re-canvassed on its way into the game; scaling it would stretch
        # the figure, so the game's own copy is recoloured instead.
        if original is not None and abs(original.width / original.height - game_copy.width / game_copy.height) < OUTFIT_COPY_SHAPE_TOLERANCE:
            source = apply_recipe(original, recipe)
            if source.size != game_copy.size:
                source = source.resize(game_copy.size, Image.LANCZOS)
        else:
            source = apply_recipe(game_copy, recipe)
        save(source, "characters", character, outfit, name)
        written.append(name)
        if name not in default_claimed:
            copied_drawings.append(name)
    write_manifest(outfit_folder, written)
    write_copies_list(outfit_folder, copied_drawings)
    return written


# The copies made from a real drawing. generate-sprite-metrics.js reads this list so the game does not
# treat them as stand-ins (the Broken tint goes on stand-ins only).
COPIES_NAME = ".copies.txt"
COPIES_HEADER = (
    "# Files in this folder that generate-placeholder-art.py copied from a DRAWING in the default outfit,\n"
    "# recoloured. They are on .generated.txt too; this list only tells the game they are not stand-ins.\n"
)


def write_copies_list(folder_path, names):
    path = os.path.join(folder_path, COPIES_NAME)
    if not names:
        if os.path.exists(path):
            os.remove(path)
        return
    with io.open(path, "w", encoding="utf-8") as handle:
        handle.write(COPIES_HEADER)
        for name in sorted(names):
            handle.write(name + "\n")


def real_image(*parts):
    """A game file that is present and NOT on its folder's manifest (a drawing), as RGBA, or None."""
    folder_path = os.path.join(ART, *parts[:-1])
    path = os.path.join(ART, *parts)
    if not os.path.exists(path) or parts[-1] in set(read_manifest(folder_path)):
        return None
    return Image.open(path).convert("RGBA")


