def draw_motif(image, motif, color):
    # Drawn on a layer and composited: a translucent fill drawn straight onto an RGBA image REPLACES the
    # pixels under it instead of blending, which left see-through holes where the motif should be.
    width, height = image.size
    layer = Image.new("RGBA", image.size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(layer)
    cx, cy = width // 2, height // 2
    unit = min(width, height)
    paint = color + (70,)
    if motif == "crossed":
        t, o = int(unit * 0.06), int(unit * 0.26)
        draw.line([cx - o, cy - o, cx + o, cy + o], fill=paint, width=t)
        draw.line([cx + o, cy - o, cx - o, cy + o], fill=paint, width=t)
    elif motif == "eye":
        r = int(unit * 0.24)
        draw.ellipse([cx - r * 1.6, cy - r, cx + r * 1.6, cy + r], outline=paint, width=int(unit * 0.045))
        draw.ellipse([cx - r * 0.45, cy - r * 0.45, cx + r * 0.45, cy + r * 0.45], fill=paint)
    elif motif == "question":
        r = int(unit * 0.2)
        draw.arc([cx - r, cy - r * 1.5, cx + r, cy + r * 0.2], start=160, end=20, fill=paint, width=int(unit * 0.055))
        draw.line([cx, cy + r * 0.1, cx, cy + r * 0.6], fill=paint, width=int(unit * 0.055))
        draw.ellipse([cx - unit * 0.035, cy + r * 0.85, cx + unit * 0.035, cy + r * 0.85 + unit * 0.07], fill=paint)
    elif motif == "chest":
        h = int(unit * 0.24)
        draw.rounded_rectangle([cx - h, cy - h * 0.55, cx + h, cy + h * 0.8], radius=int(unit * 0.03),
                               outline=paint, width=int(unit * 0.045))
        draw.line([cx - h, cy + h * 0.1, cx + h, cy + h * 0.1], fill=paint, width=int(unit * 0.04))
    elif motif == "fire":
        h = int(unit * 0.22)
        draw.polygon([(cx, cy - h * 1.3), (cx + h, cy + h * 0.6), (cx, cy + h), (cx - h, cy + h * 0.6)], outline=paint)
        draw.polygon([(cx, cy - h * 0.5), (cx + h * 0.5, cy + h * 0.6), (cx - h * 0.5, cy + h * 0.6)], fill=paint)
    elif motif == "arch":
        h = int(unit * 0.22)
        draw.arc([cx - h, cy - h, cx + h, cy + h], start=180, end=360, fill=paint, width=int(unit * 0.05))
        draw.line([cx - h, cy, cx - h, cy + h * 1.4], fill=paint, width=int(unit * 0.05))
        draw.line([cx + h, cy, cx + h, cy + h * 1.4], fill=paint, width=int(unit * 0.05))
    elif motif == "spiral":
        r = int(unit * 0.26)
        for step in range(4):
            inset = int(r * step * 0.22)
            draw.arc([cx - r + inset, cy - r + inset, cx + r - inset, cy + r - inset],
                     start=step * 90, end=step * 90 + 270, fill=paint, width=int(unit * 0.04))
    elif motif == "wisp":
        # A pale orb trailing upward: something that drifts into a deck uninvited.
        r = int(unit * 0.13)
        for ring in range(5, 0, -1):
            grow = r * (1 + ring * 0.35)
            draw.ellipse([cx - grow, cy - grow + r * 0.4, cx + grow, cy + grow + r * 0.4], fill=color + (14,))
        draw.ellipse([cx - r, cy - r + r * 0.4, cx + r, cy + r + r * 0.4], fill=color + (120,))
        draw.polygon([(cx - r * 0.7, cy), (cx, cy - r * 3.2), (cx + r * 0.7, cy)], fill=color + (60,))
    return Image.alpha_composite(image, layer.filter(ImageFilter.GaussianBlur(unit * 0.004)))


