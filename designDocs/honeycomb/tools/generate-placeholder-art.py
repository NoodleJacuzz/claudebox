def stash_sources():
    """Moves the original art into _source/ on first run, so sources and output never mix."""
    moves = [("full", "characters", SOURCE_CHARACTERS)]
    for old_folder, kind, stems in moves:
        for stem in stems:
            old = os.path.join(ART, old_folder, stem + ".webp")
            new = os.path.join(ART, SOURCE_DIR, kind, stem + ".webp")
            if os.path.exists(old) and not os.path.exists(new):
                os.makedirs(os.path.dirname(new), exist_ok=True)
                shutil.copy2(old, new)
                print("  stashed %s -> %s" % (old_folder + "/" + stem, SOURCE_DIR + "/" + kind))


def read_manifest(folder_path):
    """The files a previous run wrote into this folder, or an empty list."""
    manifest = os.path.join(folder_path, MANIFEST_NAME)
    if not os.path.exists(manifest):
        return []
    with io.open(manifest, encoding="utf-8") as handle:
        return [line.strip() for line in handle
                if line.strip() and not line.startswith("#")]


def write_manifest(folder_path, names):
    with io.open(os.path.join(folder_path, MANIFEST_NAME), "w", encoding="utf-8") as handle:
        handle.write(MANIFEST_HEADER)
        for name in sorted(names):
            handle.write(name + "\n")


def clear_previous_output(roots=None):
    """Deletes only files a previous run claimed, leaving real art and stray files alone."""
    root_array = GENERATED_ROOTS if roots is None else roots
    if FORCE:
        for root_folder in GENERATED_ROOTS:
            path = os.path.join(ART, root_folder)
            if os.path.isdir(path):
                shutil.rmtree(path)
        print("  --force: previous output cleared wholesale")
        return 0
    protected = 0
    removed = 0
    for root_folder in root_array:
        root_path = os.path.join(ART, root_folder)
        if not os.path.isdir(root_path):
            continue
        for current, _dirs, files in os.walk(root_path):
            claimed = read_manifest(current)
            if not claimed:
                # No manifest: this folder was not written by the generator. Never touch it.
                protected += len([f for f in files if f != MANIFEST_NAME])
                continue
            for name in files:
                if name == MANIFEST_NAME:
                    continue
                if name in claimed:
                    os.remove(os.path.join(current, name))
                    removed += 1
                else:
                    protected += 1
    if protected:
        print("  %d file(s) not written by this script were left untouched" % protected)
    return removed


