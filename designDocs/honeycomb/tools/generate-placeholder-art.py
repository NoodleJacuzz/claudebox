def vertical_gradient(size, top_color, bottom_color):
    image = Image.new("RGBA", size)
    draw = ImageDraw.Draw(image)
    for row in range(size[1]):
        blend = row / max(1, size[1] - 1)
        draw.line([(0, row), (size[0], row)], fill=tuple(
            int(top_color[c] + (bottom_color[c] - top_color[c]) * blend) for c in range(3)) + (255,))
    return image


def add_pillars(image, count, color, alpha, seed):
    width, height = image.size
    layer = Image.new("RGBA", image.size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(layer)
    state = seed
    for index in range(count):
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        centre = int(width * (index + 0.5) / count + ((state >> 8) % max(1, width // count)) - width // (count * 2))
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        half = int(width * 0.02) + int((state >> 8) % max(1, int(width * 0.035)))
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        top = int(height * 0.05) + int((state >> 8) % max(1, int(height * 0.3)))
        draw.rounded_rectangle([centre - half, top, centre + half, height], radius=half,
                               fill=color + (alpha,))
    return Image.alpha_composite(image, layer.filter(ImageFilter.GaussianBlur(width * 0.006)))


def add_glow(image, points, color, radius_fraction, alpha):
    width, height = image.size
    layer = Image.new("RGBA", image.size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(layer)
    radius = int(min(width, height) * radius_fraction)
    for (fx, fy) in points:
        x, y = int(width * fx), int(height * fy)
        draw.ellipse([x - radius, y - radius, x + radius, y + radius], fill=color + (alpha,))
    return Image.alpha_composite(image, layer.filter(ImageFilter.GaussianBlur(radius * 0.6)))


