# THE EXPOSED CUT-IN'S TITLE (session 21). "EXPOSED" in the display font, white over a rose glow, on
# transparent. A hand-drawn ui/exposed/exposedText.png wins under the usual rule. UI frames and other
# ui/ assets are not part of clear_previous_output's character/enemy sweep, so this checks its own
# target and keeps a real file.
EXPOSED_TEXT_CANVAS = (1400, 420)
EXPOSED_TEXT_SIZE = 232
EXPOSED_TEXT_GLOW = (255, 52, 104)
EXPOSED_TEXT_BLUR = 30


def build_exposed_text():
    print("Exposed cut-in title:")
    output_relative = "ui/exposed/exposedText.webp"
    output_path = os.path.join(ART, *output_relative.split("/"))
    drawn_path = os.path.join(ART, "ui", "exposed", "exposedText.png")
    if os.path.exists(drawn_path):
        save(Image.open(drawn_path).convert("RGBA"), *output_relative.split("/"))
        print("  ", output_relative, "(converted from exposedText.png)")
        return
    if os.path.exists(output_path) and not FORCE:
        print("  ", output_relative, "(kept)")
        return
    width, height = EXPOSED_TEXT_CANVAS
    layer = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    draw = ImageDraw.Draw(layer)
    font = label_font(EXPOSED_TEXT_SIZE)
    text = "EXPOSED"
    text_width = draw.textlength(text, font=font)
    draw.text(((width - text_width) / 2, height * 0.20), text, font=font, fill=(255, 246, 250, 255))
    glow = layer.filter(ImageFilter.GaussianBlur(EXPOSED_TEXT_BLUR))
    rose = Image.new("RGBA", (width, height), EXPOSED_TEXT_GLOW + (255,))
    rose.putalpha(glow.getchannel("A"))
    save(Image.alpha_composite(rose, layer), *output_relative.split("/"))
    print("  ", output_relative, "(stand-in)")


def build_broken_masks():
    print("Broken cut-in masks:")
    for source_relative, output_relative in BROKEN_MASK_ARRAY:
        source_path = os.path.join(ART, *source_relative.split("/"))
        if not os.path.exists(source_path):
            print("  MISSING", source_relative)
            continue
        source = Image.open(source_path).convert("RGBA")
        alpha = source.split()[3]
        # The complement: white where the original was transparent, transparent where it was opaque.
        inverted = ImageOps.invert(alpha)
        result = Image.merge("RGBA", (
            Image.new("L", source.size, 255),
            Image.new("L", source.size, 255),
            Image.new("L", source.size, 255),
            inverted,
        ))
        save(result, *output_relative.split("/"))
        print("  ", output_relative)


# THE LEWD SUPERTYPE'S OWN FRAME AND ICON (round 06, item 11).
# > Finally, lewd cards should have their own cardframe and icon as one of the game's supertypes.
# Stand-ins only: the shared placeholder frames pushed into the lust palette with a heart on each corner,
# and heart-red recoloured pink with a keyhole cut through it (heart-glow-pink is Regeneration's). A drawn
# .png beside a target wins, and an existing .webp is kept without --force, as with every generated asset.
LEWD_FRAME_ARRAY = [
    ("cards/frames/placeholderVertical.webp", "cards/frames/lewdVertical.webp"),
    ("cards/frames/placeholderHorizontal.webp", "cards/frames/lewdHorizontal.webp"),
]
LEWD_ICON = ("icons/heart-red.webp", "icons/type-lewd.webp")
LEWD_HUE_SHIFT_DEGREES = 295
LEWD_CORNER_HEART_FRACTION = 0.085
LEWD_CORNER_INSET_FRACTION = 0.004
LEWD_PINK = (255, 95, 210)
LEWD_KEYHOLE_COLOR = (58, 10, 40, 255)


def lewd_target_is_free(output_relative):
    output_path = os.path.join(ART, *output_relative.split("/"))
    drawn_path = output_path[:-len(".webp")] + ".png"
    if os.path.exists(drawn_path):
        save(Image.open(drawn_path).convert("RGBA"), *output_relative.split("/"))
        print("  ", output_relative, "(converted from .png)")
        return False
    if os.path.exists(output_path) and not FORCE:
        print("  ", output_relative, "(kept)")
        return False
    return True


def lewd_heart_icon():
    heart = Image.open(os.path.join(ART, *LEWD_ICON[0].split("/"))).convert("RGBA")
    pink = adjust(shift_hue(heart, -30), saturation=1.15, brightness=1.08)
    pink = tint(pink, LEWD_PINK, 0.25)
    draw = ImageDraw.Draw(pink)
    width, height = pink.size
    centre_x = width * 0.5
    circle_top = height * 0.36
    radius = width * 0.075
    draw.ellipse([centre_x - radius, circle_top, centre_x + radius, circle_top + radius * 2], fill=LEWD_KEYHOLE_COLOR)
    draw.polygon([
        (centre_x - radius * 0.55, circle_top + radius * 1.4),
        (centre_x + radius * 0.55, circle_top + radius * 1.4),
        (centre_x + radius * 1.0, circle_top + radius * 4.2),
        (centre_x - radius * 1.0, circle_top + radius * 4.2),
    ], fill=LEWD_KEYHOLE_COLOR)
    return pink


def build_lewd_card_type():
    print("Lewd supertype frame and icon:")
    heart = lewd_heart_icon()
    if lewd_target_is_free(LEWD_ICON[1]):
        save(heart, *LEWD_ICON[1].split("/"))
        print("  ", LEWD_ICON[1], "(stand-in)")
    for source_relative, output_relative in LEWD_FRAME_ARRAY:
        if not lewd_target_is_free(output_relative):
            continue
        source = Image.open(os.path.join(ART, *source_relative.split("/"))).convert("RGBA")
        frame = adjust(shift_hue(source, LEWD_HUE_SHIFT_DEGREES), saturation=1.1, brightness=1.02)
        size = int(frame.size[0] * LEWD_CORNER_HEART_FRACTION)
        inset = int(frame.size[0] * LEWD_CORNER_INSET_FRACTION)
        small = heart.resize((size, size), Image.LANCZOS)
        for corner_x in (inset, frame.size[0] - size - inset):
            for corner_y in (inset, frame.size[1] - size - inset):
                frame.alpha_composite(small, (corner_x, corner_y))
        save(frame, *output_relative.split("/"))
        print("  ", output_relative, "(stand-in)")


# DOWNSAMPLED CARD FRAMES (session 15, round 07 C). Must match tuning.art.cardFrame.frameSuffixBySize.
# The full 1992x2540 frames stay as the sources; each card size draws a copy at a share of their width.
CARD_FRAME_SIZE_SHARES = [("-small", 1 / 6), ("-medium", 1 / 3), ("-large", 1 / 2)]


def build_card_frame_sizes():
    folder = art_path("cards", "frames")
    suffixes = tuple(suffix for suffix, _ in CARD_FRAME_SIZE_SHARES)
    for name in sorted(os.listdir(folder)):
        stem, extension = os.path.splitext(name)
        if extension.lower() != ".webp" or stem.endswith(suffixes):
            continue
        with Image.open(os.path.join(folder, name)) as source:
            source = source.convert("RGBA")
            for suffix, share in CARD_FRAME_SIZE_SHARES:
                width = max(1, round(source.size[0] * share))
                height = max(1, round(source.size[1] * share))
                source.resize((width, height), Image.LANCZOS).save(
                    os.path.join(folder, stem + suffix + ".webp"), "WEBP", quality=WEBP_QUALITY, method=6)
                print("  ", "cards/frames/" + stem + suffix, "%dx%d" % (width, height))


def main():
    global FORCE
    FORCE = "--force" in sys.argv
    print("Generating Honeycomb placeholder art into:", ART)
