//===================================================================================================
//HONEYCOMB ART PIPELINE -- pose shortcut rules (step 6 of BRIEF.md)
//===================================================================================================
//Step 5 left the templates as JS tables (pose-templates.js). Step 6 makes a person able to TYPE them:
//`.hcKnightV, default, PoseDefense` instead of thirty tags. The rules are generated from the same tables,
//never hand-written, so a new character or a changed template is a `--write` and nothing else.
//
//WHERE EACH LAYER GOES (BRIEF round 2: global template in cleaningDB, exceptions on the entry):
//
//  cleaningArrayInitial   one rule per slot, the CORE layer: what EVERY character does, plus `solo, simple
//                         background, white background`. It KEEPS the `Pose…` token (the first replacement is
//                         the token itself) so the character's own rule can still see it in Phase 4. It sits at
//                         the TOP of Initial so the tags it injects are cleaned by every later rule, exactly as
//                         typed tags are.
//  charactersDB entry     one rule per character, sex and slot: METHOD + SEX + `'male only'` + DROP. Entry
//                         replacement targets are lowercased by the engine, so `PoseDefense` is matched as
//                         `posedefense` and the Capitalized spelling typed by a person still lands.
//  charactersDB *outfit   `TornDamage; <torn garments>` — damage belongs to the outfit (BRIEF round 2). The
//                         CORE rule emits the `TornDamage` marker on every damaged slot.
//  cleaningArrayFinal     a purge of the bare `Pose…` token, so a shortcut typed with no character (or an
//                         unknown one) does not reach the model as a literal unknown tag.
//
//The rules are injected into RUNTIME copies of the two dictionary files for the verification pass, so a table
//change can be tried before it is written. `--write` then persists them between GENERATED sentinels, which
//makes a second run replace the block instead of appending a second one.
//
//  node --max-old-space-size=2048 "!designDocs/honeycomb/art_pipeline/refs-shortcuts.js"            verify
//  node --max-old-space-size=2048 "!designDocs/honeycomb/art_pipeline/refs-shortcuts.js" --write    persist
//
//VERIFY compiles every slot twice — the template input from pose-templates.js and the shortcut input — and
//reports the tags each path resolved differently. A difference is either an engine law (the insertion gate's
//exclusivity, or a Phase-2 tag injected one phase too late) or a bug; step 7 owns the judgement.
const fs = require("fs");
const vm = require("vm");
const path = require("path");
const templates = require("./pose-templates.js");

const ROOT = path.join(__dirname, "..", "..", "..");
const ENGINE = path.join(ROOT, "scripts", "webui");
const LIB = path.join(ENGINE, "libraries");
const CLEANING = path.join(LIB, "cleaningDB.js");
const CHARACTERS = path.join(LIB, "charactersDB.js");

const CORE_BACKGROUND = ["solo", "simple background", "white background"];
const CORE_SENTINEL = "---------------------- Honeycomb pose templates (GENERATED by refs-shortcuts.js) ----------------------";
const CORE_END = "---------------------- end Honeycomb pose templates ----------------------";
const PURGE_SENTINEL = "---------------------- Honeycomb pose purge (GENERATED) ----------------------";
const PURGE_END = "---------------------- end Honeycomb pose purge ----------------------";
const METHOD_SENTINEL = "// Honeycomb pose methods (GENERATED by refs-shortcuts.js) ";
const METHOD_END = "// end Honeycomb pose methods ";
const DAMAGE_SENTINEL = "// Honeycomb pose damage (GENERATED by refs-shortcuts.js) ";
const DAMAGE_END = "// end Honeycomb pose damage ";

const SEX_TAGS = (character, sex, slot) => templates.resolveSexStates(templates.SEX[character][slot] || templates.SEX[character][templates.SEX_LEVEL[slot]] || [], sex);

// ---- the rule data, straight from the step 5 tables -----------------------
function buildBlocks() {
	const core = [CORE_SENTINEL, "-/ Honeycomb pose templates"];
	const purge = [PURGE_SENTINEL, "-/ Honeycomb pose purge"];
	for (const slot of templates.SLOT_ARRAY) {
		const token = templates.POSE_TOKEN[slot];
		core.push(token + "; " + [token].concat(templates.CORE[slot], CORE_BACKGROUND).join(", "));
		purge.push(token + ";");
	}
	core.push(CORE_END);
	purge.push(PURGE_END);

	const methods = {}; const damage = {};
	for (const character of Object.keys(templates.ENTRY)) {
		for (const sex of ["V", "C"]) {
			const key = templates.ENTRY[character] + sex;
			const lines = [METHOD_SENTINEL + key];
			for (const slot of templates.SLOT_ARRAY) {
				const list = (templates.methodFor(character, slot) || []).slice();
				if (templates.DAMAGED_SLOTS.includes(slot)) { list.push("TornDamage"); }
				list.push(...SEX_TAGS(character, sex, slot));
				list.push(...((templates.DROP[character] || {})[slot] || []));
				lines.push(templates.POSE_TOKEN[slot] + "; " + list.join(", "));
			}
			lines.push(METHOD_END + key);
			methods[key] = lines;
			damage[key] = templates.DAMAGE[character] && templates.DAMAGE[character].length
				? [DAMAGE_SENTINEL + key, "TornDamage; " + templates.DAMAGE[character].join(", "), DAMAGE_END + key] : [];
		}
	}
	return { core, purge, methods, damage };
}

// ---- injecting a block into a source string ------------------------------
// Found between its two sentinels: replace. Not found: insert after `anchor`.
function replaceBetween(source, startSentinel, endSentinel, block) {
	const start = source.indexOf(startSentinel);
	if (start < 0) { return null; }
	const end = source.indexOf(endSentinel, start);
	if (end < 0) { throw new Error("unterminated GENERATED block: " + startSentinel); }
	return source.slice(0, start) + block.join("\n") + source.slice(end + endSentinel.length);
}

function insertAfter(source, anchor, block) {
	const at = source.indexOf(anchor);
	if (at < 0) { throw new Error("anchor not found: " + JSON.stringify(anchor)); }
	return source.slice(0, at + anchor.length) + block.join("\n") + "\n" + source.slice(at + anchor.length);
}

function injectedSources(blocks) {
	let cleaning = fs.readFileSync(CLEANING, "utf8");
	const coreDone = replaceBetween(cleaning, CORE_SENTINEL, CORE_END, blocks.core);
	cleaning = coreDone != null ? coreDone : insertAfter(cleaning, "var cleaningArrayInitial = `\r\n", blocks.core);
	const purgeDone = replaceBetween(cleaning, PURGE_SENTINEL, PURGE_END, blocks.purge);
	if (purgeDone != null) { cleaning = purgeDone; }
	else {
		const closed = cleaning.lastIndexOf("`;");
		cleaning = cleaning.slice(0, closed) + blocks.purge.join("\n") + "\n" + cleaning.slice(closed);
	}

	let characters = fs.readFileSync(CHARACTERS, "utf8");
	for (const [entry, block] of Object.entries(blocks.methods)) {
		const replaced = replaceBetween(characters, METHOD_SENTINEL + entry, METHOD_END + entry, block);
		if (replaced != null) { characters = replaced; continue; }
		const at = characters.indexOf(entry + ";");
		const entryLine = characters.slice(at, characters.indexOf("\n", at) + 1);
		characters = insertAfter(characters, entryLine, block);
	}
	for (const [entry, block] of Object.entries(blocks.damage)) {
		if (!block.length) { continue; }
		const replaced = replaceBetween(characters, DAMAGE_SENTINEL + entry, DAMAGE_END + entry, block);
		if (replaced != null) { characters = replaced; continue; }
		const at = characters.indexOf(entry + ";");
		const defaultLine = characters.slice(at, characters.indexOf("\n", characters.indexOf("*default;", at)) + 1);
		characters = insertAfter(characters, defaultLine, block);
	}
	// The blocks join on \n; the dictionaries are CRLF. Keep each file on its own newline so a write does not
	// leave half the file LF and half CRLF.
	const sameNewline = (text, file) => fs.readFileSync(file, "utf8").includes("\r\n")
		? text.replace(/\r\n/g, "\n").replace(/\n/g, "\r\n") : text;
	return { cleaning: sameNewline(cleaning, CLEANING), characters: sameNewline(characters, CHARACTERS) };
}

function loadSandbox(sources) {
	const quiet = { log() {}, info() {}, warn() {}, debug() {}, error: console.error };
	const sandbox = { console: quiet, module: undefined };
	vm.createContext(sandbox);
	const webuiSource = fs.readFileSync(path.join(ENGINE, "webui.js"), "utf8");
	const libraryList = webuiSource.match(/var\s+librariesList\s*=\s*\[([\s\S]*?)\]/)[1].match(/"([^"]+)"/g).map((q) => q.slice(1, -1));
	for (const file of libraryList) {
		let src = fs.readFileSync(path.join(LIB, file), "utf8");
		if (file === "cleaningDB.js") { src = sources.cleaning; }
		if (file === "charactersDB.js") { src = sources.characters; }
		vm.runInContext(src, sandbox, { filename: file });
	}
	for (const file of ["webui.js", "webui2-categories.js", "webui2.js"]) vm.runInContext(fs.readFileSync(path.join(ENGINE, file), "utf8"), sandbox, { filename: file });
	vm.runInContext("v2EnsureDictionaries()", sandbox);
	return sandbox;
}

const tagsOf = (prompt) => prompt.split(/,\s*|\n/).map((tag) => tag.trim().replace(/^\(+|\)+$/g, "").replace(/:[\d.]+$/, "")).filter(Boolean);

module.exports = { buildBlocks, injectedSources, loadSandbox, tagsOf, CLEANING, CHARACTERS };
if (require.main !== module) return;

// ---- run ------------------------------------------------------------------
const blocks = buildBlocks();
const sources = injectedSources(blocks);

if (process.argv.includes("--write")) {
	const stamp = new Date().toISOString().replace(/[:.]/g, "-");
	const backup = path.join(ENGINE, "_backups");
	fs.mkdirSync(backup, { recursive: true });
	for (const file of ["cleaningDB.js", "charactersDB.js"]) {
		fs.copyFileSync(path.join(LIB, file), path.join(backup, file.replace(/\.js$/, "." + stamp + ".shortcuts.js")));
	}
	fs.writeFileSync(CLEANING, sources.cleaning, "utf8");
	fs.writeFileSync(CHARACTERS, sources.characters, "utf8");
	console.log("wrote cleaningDB.js and charactersDB.js (" + Object.keys(blocks.methods).length + " entries); backups in scripts/webui/_backups/");
}

const sandbox = loadSandbox(sources);
let match = 0; const failures = [];
for (const character of Object.keys(templates.ENTRY)) {
	for (const sex of ["V", "C"]) {
		for (const slot of templates.SLOT_ARRAY) {
			const template = sandbox.buildPrompt(templates.buildInput(character, sex, slot), "", {});
			const shortcut = sandbox.buildPrompt(templates.buildShortcutInput(character, sex, slot), "", {});
			const want = new Set(tagsOf(template.prompt)), got = new Set(tagsOf(shortcut.prompt));
			const missing = [...want].filter((tag) => !got.has(tag));
			const extra = [...got].filter((tag) => !want.has(tag));
			const name = character + "1" + sex + "-" + templates.FILE_SLOT[slot];
			if (!missing.length && !extra.length) { match++; continue; }
			failures.push({ name, missing, extra });
		}
	}
}
console.log("\n### Shortcut vs template (" + match + "/" + (match + failures.length) + " slots identical)");
for (const fail of failures) {
	console.log("  " + fail.name.padEnd(22) + (fail.missing.length ? "template-only: " + fail.missing.join(", ") : "") +
		(fail.extra.length ? (fail.missing.length ? " | " : "") + "shortcut-only: " + fail.extra.join(", ") : ""));
}
if (failures.length) {
	console.log("\nEach difference is the insertion gate resolving a mutually-exclusive expression pair differently from a");
	console.log("typed tag, or a Phase-2 tag (solo determination) injected in Phase 4. Step 7 owns the verdicts.");
}
